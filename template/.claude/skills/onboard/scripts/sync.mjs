#!/usr/bin/env node
// spec-first-kit. Generates the files that are derived from .claude/, the single source of truth.
// Always, in a monorepo:
//   .claude/settings.json       → <package>/.claude/settings.json for each folder in "packages" of .claude/sdd.json:
//                                 a monorepo package where Claude Code starts runs the root hooks through it
// Only with "codex": true in .claude/sdd.json, the Codex copies:
//   .claude/skills/<name>/      → .agents/skills/<name>/   SKILL.md frontmatter cut to the Agent Skills fields;
//                                                          disable-model-invocation → agents/openai.yaml policy
//   .claude/agents/<name>.md    → .codex/agents/<name>.toml
//   .claude/settings.json hooks → .codex/hooks.json        tool names mapped to Codex (Edit/Write → apply_patch);
//                                                          paths resolved from the git root, with a Windows variant;
//                                                          Edit(...) entries of permissions.deny → protect.mjs hook
//   .claude/rules/*.md          → the Codex block in AGENTS.md, between the spec-first-kit:path-rules markers
//                                 (Codex reads only AGENTS.md files, and only from the root down to where it starts)
// With "codex": false the copies it generated before are deleted and the AGENTS.md block is emptied.
// Never edit the generated files: edit .claude/ and run this again.
// Ownership: "generated" in .claude/sdd.lock.json records every file this script wrote and its hash. A file it did
// not write is never replaced (unless --force) and never deleted; a copy that was edited by hand is backed up before
// it is replaced or deleted. Backups go to .claude/.cache/kit-backup/<time>/.
//
// Usage: node .claude/skills/onboard/scripts/sync.mjs [--check] [--force] [--dir <repo>]
//   --check  exit 1 and list the files that differ, write nothing (for CI and the session-start hook)
//   --force  also replace files that exist but were not generated by the kit (each one is backed up first)
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, realpathSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { splitFrontmatter, field, value, list } from './frontmatter.mjs';

const LOCK = '.claude/sdd.lock.json';
const GENERATOR = '.claude/skills/onboard/scripts/sync.mjs';
const BACKUP = '.claude/.cache/kit-backup';
const RULES = ['<!-- spec-first-kit:path-rules -->', '<!-- /spec-first-kit:path-rules -->'];
const SKILL_FIELDS = ['license', 'compatibility', 'metadata']; // Agent Skills fields copied through as written
const HOOK_EVENTS = ['SessionStart', 'PreToolUse', 'PostToolUse', 'UserPromptSubmit', 'Stop'];
const EFFORT = { minimal: 'minimal', low: 'low', medium: 'medium', high: 'high', xhigh: 'xhigh', max: 'xhigh' };
// Claude Code tool names in a matcher → Codex. File edits are one apply_patch tool there; Codex has no PowerShell tool.
const CODEX_TOOL = { Bash: 'Bash', PowerShell: null, Edit: 'apply_patch', Write: 'apply_patch', MultiEdit: 'apply_patch' };

const posix = (p) => p.replace(/\\/g, '/');
const read = (p) => readFileSync(p, 'utf8');
const hash = (data) => createHash('sha256').update(data).digest('hex');
const bytes = (c) => (Buffer.isBuffer(c) ? c : Buffer.from(c, 'utf8'));
// git with core.autocrlf=true (the Git for Windows default) checks text files out with CRLF, so a copy is compared
// and hashed with LF line endings; a file with a NUL byte is binary and stays as it is.
const lf = (c) => { const b = bytes(c); return b.includes(0) ? b : Buffer.from(b.toString('utf8').replace(/\r\n/g, '\n'), 'utf8'); };
const sameHash = (stored, disk) => stored === hash(lf(disk));

function walk(root, base = root) {
  const out = [];
  for (const e of readdirSync(root, { withFileTypes: true })) {
    const p = join(root, e.name);
    if (e.isDirectory()) out.push(...walk(p, base));
    else if (!/(^\.DS_Store$|\.bak$|\.kit-new$|~$)/.test(e.name)) out.push(posix(relative(base, p)));
  }
  return out;
}

function skillMd(name, text) {
  const fm = splitFrontmatter(text);
  const description = [value(fm, 'description'), value(fm, 'when_to_use')].filter(Boolean).join(' ');
  const lines = ['---', `# Generated from .claude/skills/${name}/SKILL.md by ${GENERATOR}. Edit the source, then re-run it.`,
    `name: ${JSON.stringify(value(fm, 'name') || name)}`, `description: ${JSON.stringify(description)}`];
  for (const key of SKILL_FIELDS) { const f = field(fm, key); if (f) lines.push(...f.lines); }
  lines.push('---', '');
  return { text: lines.join('\n') + fm.body, manualOnly: value(fm, 'disable-model-invocation') === true };
}

function tomlString(s) {
  return JSON.stringify(s); // JSON escapes are valid TOML basic-string escapes
}

function tomlMultiline(s) {
  if (!s.includes("'''")) return `'''\n${s}'''`;
  return `"""\n${s.replace(/\\/g, '\\\\').replace(/"""/g, '""\\"')}"""`;
}

function agentToml(file, text) {
  const fm = splitFrontmatter(text);
  const name = value(fm, 'name') || file.replace(/\.md$/, '');
  const tools = String(value(fm, 'tools') || '');
  const notes = ['Codex note: tool names below come from Claude Code (Read, Edit, Grep, Glob, Bash, Skill): use your',
    'equivalents. Skills live in .agents/skills/. Hooks that Claude Code scopes to this agent do not run in Codex.'];
  if (tools && !/\b(Edit|Write|MultiEdit)\b/.test(tools)) notes.push('You are read-only: never modify files; the shell is for reads and tests only.');
  const lines = [`# Generated from .claude/agents/${file} by ${GENERATOR}. Edit the source, then re-run it.`,
    `name = ${tomlString(name)}`, `description = ${tomlString(String(value(fm, 'description') || ''))}`];
  const model = value(fm, 'codexModel'); // optional: without it the agent uses the Codex session model
  if (model) lines.push(`model = ${tomlString(String(model))}`);
  const effort = EFFORT[String(value(fm, 'codexEffort') || value(fm, 'effort') || '')];
  if (effort) lines.push(`model_reasoning_effort = ${tomlString(effort)}`);
  lines.push(`developer_instructions = ${tomlMultiline(`${notes.join('\n')}\n\n${fm.body.trim()}\n`)}`, '');
  return { name, text: lines.join('\n') };
}

// Codex has no project-dir variable and may start in a subdirectory, so commands find the repo root themselves.
// POSIX shells: $(git rev-parse --show-toplevel), as the Codex docs suggest. Windows (commandWindows): a one-off git
// alias, because git runs "!" aliases from the repository root through its own sh; the same string works when Codex
// hands it to PowerShell or to cmd.exe, and stdin, stdout and the exit code pass through.
function codexCommands(h) {
  const root = '$(git rev-parse --show-toplevel)';
  const fix = (s) => String(s).replace(/\$\{CLAUDE_PROJECT_DIR\}|\$CLAUDE_PROJECT_DIR/g, root);
  const parts = [h.command, ...(h.args || [])].map(fix);
  const out = { command: parts.map((p) => (/\s|\$\(/.test(p) ? `"${p}"` : p)).join(' ') };
  const rel = (h.args || []).map(String).map((a) => a.match(/^\$\{CLAUDE_PROJECT_DIR\}\/(.+)$/)?.[1]).filter(Boolean);
  if (h.command === 'node' && h.args?.length === 1 && rel.length === 1 && !/[\s"!]/.test(rel[0])) {
    out.commandWindows = `git -c "alias.kit-hook=!node ${rel[0]}" kit-hook`;
  }
  return out;
}

// A tool matcher in Codex terms; '' when none of its tools exist in Codex. Other events keep their matcher.
function codexMatcher(event, m) {
  if (!m || !/ToolUse$/.test(event)) return m;
  return [...new Set(m.split('|').map((n) => (n in CODEX_TOOL ? CODEX_TOOL[n] : n)).filter(Boolean))].join('|');
}

const handler = (h) => ({ type: 'command', ...codexCommands(h), ...(h.timeout ? { timeout: h.timeout } : {}) });

function hooksJson(dir, settings) {
  const hooks = {};
  for (const event of HOOK_EVENTS) {
    const groups = (settings.hooks?.[event] || []).map((g) => {
      const matcher = codexMatcher(event, g.matcher);
      const handlers = (g.hooks || []).filter((h) => h.type === 'command').map(handler);
      return handlers.length && matcher !== '' ? { ...(matcher ? { matcher } : {}), hooks: handlers } : null;
    }).filter(Boolean);
    if (groups.length) hooks[event] = groups;
  }
  // Claude Code enforces permissions.deny itself; in Codex the Edit(...) entries become a hook on apply_patch.
  const denyEdits = (settings.permissions?.deny || []).some((d) => /^(Edit|Write)\(/.test(d));
  if (denyEdits && existsSync(join(dir, '.claude', 'hooks', 'protect.mjs'))) {
    const protect = { matcher: 'apply_patch', hooks: [handler({ command: 'node', args: ['${CLAUDE_PROJECT_DIR}/.claude/hooks/protect.mjs'], timeout: 10 })] };
    hooks.PreToolUse = [...(hooks.PreToolUse || []), protect];
  }
  return { description: `Generated from .claude/settings.json by ${GENERATOR}. Edit the source, then re-run it.`, hooks };
}

// AGENTS.md with the Codex block regenerated, or null when nothing changes. With Codex the block names the generated
// copies and lists the path rules (Codex has no path rules of its own); it is inserted under "## Conventions" when the
// markers are missing. Without Codex an existing block is emptied: the markers are HTML comments, which Claude Code
// leaves out of the context.
function agentsMd(dir, codex) {
  const path = join(dir, 'AGENTS.md');
  if (!existsSync(path)) return null;
  const text = read(path);
  const start = text.indexOf(RULES[0]), end = text.indexOf(RULES[1]);
  const marked = start >= 0 && end > start;
  if (!marked && !codex) return null;
  const eol = text.includes('\r\n') ? '\r\n' : '\n';
  const root = join(dir, '.claude', 'rules');
  const rows = (existsSync(root) ? walk(root).filter((f) => f.endsWith('.md')).sort() : []).map((f) => {
    const paths = list(splitFrontmatter(read(join(root, f))), 'paths');
    return `- ${paths.length ? paths.map((p) => `\`${p}\``).join(', ') : 'every file'} → \`.claude/rules/${f}\``;
  });
  const lines = !codex ? [] : [
    `Codex: \`.agents/skills/\` and \`.codex/\` are generated from \`.claude/\` by \`node ${GENERATOR}\`; never edit them.`,
    ...(rows.length ? ['Before editing a file, read the rule for its path (Claude Code loads it by itself):', ...rows] : [])];
  const block = [RULES[0], ...lines, RULES[1]].join(eol);
  if (marked) return text.slice(0, start) + block + text.slice(end + RULES[1].length);
  const heading = text.match(/^## Conventions[^\n]*\n/m);
  if (!heading) return `${text.replace(/\s*$/, '')}${eol}${eol}${block}${eol}`;
  const at = heading.index + heading[0].length;
  return `${text.slice(0, at)}${eol}${block}${eol}${text.slice(at)}`;
}

export function config(dir) {
  try { return JSON.parse(read(join(dir, '.claude', 'sdd.json'))); } catch { return {}; }
}

// The "packages" list of sdd.json: folders of a monorepo where people start Claude Code. "dir/*" means every
// subfolder of dir. Returns each entry with the folders it matched, or an error when the value is not a list.
export function packageEntries(dir) {
  const value = config(dir).packages;
  if (value === undefined) return { entries: [] };
  if (!Array.isArray(value) || value.some((p) => typeof p !== 'string')) return { error: 'packages must be a list of folder paths', entries: [] };
  const entries = value.map((pattern) => {
    const clean = posix(pattern).replace(/^\.\//, '').replace(/\/+$/, '');
    let dirs = [];
    if (clean.endsWith('/*')) {
      const base = clean.slice(0, -2), abs = join(dir, base);
      if (existsSync(abs)) dirs = readdirSync(abs, { withFileTypes: true }).filter((e) => e.isDirectory() && !e.name.startsWith('.')).map((e) => `${base}/${e.name}`);
    } else if (existsSync(join(dir, clean)) && statSync(join(dir, clean)).isDirectory()) dirs = [clean];
    return { pattern, dirs: dirs.filter((d) => d && d !== '.' && !d.startsWith('..')) };
  });
  return { entries };
}

// Claude Code reads .claude/settings.json only from the folder it starts in, so a session started in a package would
// run none of the kit's hooks and none of its Read denies. A package stub runs the root's hook scripts by a relative
// path (they find the kit root from their own location) and repeats the Read(...) denies. The root's Edit(...) denies
// point outside the package, where Claude Code asks before every edit anyway.
function packageSettings(settings, pkg) {
  const kitHook = /^\$\{CLAUDE_PROJECT_DIR\}\/\.claude\/hooks\//;
  const up = pkg.split('/').map(() => '..').join('/');
  const hooks = {};
  for (const [event, groups] of Object.entries(settings.hooks || {})) {
    const kept = groups.map((g) => ({ ...g, hooks: (g.hooks || []).filter((h) => (h.args || []).some((a) => kitHook.test(a)))
      .map((h) => ({ ...h, args: h.args.map((a) => String(a).replace(kitHook, `\${CLAUDE_PROJECT_DIR}/${up}/.claude/hooks/`)) })) }))
      .filter((g) => g.hooks.length);
    if (kept.length) hooks[event] = kept;
  }
  const deny = (settings.permissions?.deny || []).filter((d) => d.startsWith('Read('));
  return { ...(settings.$schema ? { $schema: settings.$schema } : {}), permissions: { deny }, hooks };
}

// Everything this script would write: Map<repo-relative path, string | Buffer>.
export function plan(dir) {
  const files = new Map();
  const codex = config(dir).codex === true;
  const skillsDir = join(dir, '.claude', 'skills');
  if (codex && existsSync(skillsDir)) {
    for (const e of readdirSync(skillsDir, { withFileTypes: true })) {
      if (!e.isDirectory() || !existsSync(join(skillsDir, e.name, 'SKILL.md'))) continue;
      const src = join(skillsDir, e.name);
      const rel = walk(src);
      for (const f of rel) {
        const out = `.agents/skills/${e.name}/${f}`;
        if (f === 'SKILL.md') {
          const s = skillMd(e.name, read(join(src, f)));
          files.set(out, s.text);
          if (s.manualOnly && !rel.includes('agents/openai.yaml')) {
            files.set(`.agents/skills/${e.name}/agents/openai.yaml`, '# Generated: the Claude Code skill sets disable-model-invocation.\npolicy:\n  allow_implicit_invocation: false\n');
          }
        } else files.set(out, readFileSync(join(src, f)));
      }
    }
  }
  const agentsDir = join(dir, '.claude', 'agents');
  if (codex && existsSync(agentsDir)) {
    for (const f of readdirSync(agentsDir).filter((n) => n.endsWith('.md'))) {
      const a = agentToml(f, read(join(agentsDir, f)));
      files.set(`.codex/agents/${a.name}.toml`, a.text);
    }
  }
  const settingsPath = join(dir, '.claude', 'settings.json');
  if (existsSync(settingsPath)) {
    const settings = JSON.parse(read(settingsPath));
    if (codex) files.set('.codex/hooks.json', `${JSON.stringify(hooksJson(dir, settings), null, 2)}\n`);
    for (const pkg of new Set(packageEntries(dir).entries.flatMap((e) => e.dirs))) {
      files.set(`${pkg}/.claude/settings.json`, `${JSON.stringify(packageSettings(settings, pkg), null, 2)}\n`);
    }
  }
  const agents = agentsMd(dir, codex);
  if (agents !== null) files.set('AGENTS.md', agents);
  return files;
}

const readLock = (dir) => { try { return JSON.parse(read(join(dir, LOCK))); } catch { return null; } };

// Path → hash of every file the last run wrote.
const previous = (dir) => readLock(dir)?.generated || {};

// same: nothing to do. write: new file or an untouched copy of ours. replace: our copy, edited by hand (back it up).
// conflict: a file the kit did not write. AGENTS.md is the project's: only its marked block changes.
function classify(dir, path, content, prev) {
  const abs = join(dir, path);
  if (!existsSync(abs)) return 'write';
  const disk = readFileSync(abs);
  if (lf(disk).equals(lf(content))) return 'same';
  if (path === 'AGENTS.md') return 'write';
  if (path in prev) return sameHash(prev[path], disk) ? 'write' : 'replace';
  return 'conflict';
}

function survey(dir) {
  const files = plan(dir), prev = previous(dir);
  const kinds = new Map([...files.keys()].map((p) => [p, classify(dir, p, files.get(p), prev)]));
  const gone = Object.keys(prev).filter((p) => !files.has(p) && existsSync(join(dir, p)));
  return { files, prev, kinds, gone };
}

// Paths that are missing, differ, or should be deleted. Empty means the copies are current.
export function stale(dir) {
  const { kinds, gone } = survey(dir);
  return [...[...kinds].filter(([, k]) => k === 'write' || k === 'replace').map(([p]) => p), ...gone];
}

// Files the kit would generate but that exist and were not generated by it.
export function conflicts(dir) {
  return [...survey(dir).kinds].filter(([, k]) => k === 'conflict').map(([p]) => p);
}

// Removes the folders a deleted file leaves empty, up to the repository root.
function prune(dir, abs) {
  for (let d = dirname(abs); ; d = dirname(d)) {
    const r = posix(relative(dir, d));
    if (!r || r.startsWith('..') || r === '.claude' || readdirSync(d).length) break;
    rmSync(d, { recursive: true });
  }
}

function writeLock(dir, generated) {
  const lock = readLock(dir);
  if (!lock && !Object.keys(generated).length) return;
  const next = `${JSON.stringify({ ...lock, generated }, null, 2)}\n`;
  const path = join(dir, LOCK);
  if (!existsSync(path) || !lf(readFileSync(path)).equals(lf(next))) writeFileSync(path, next);
}

function write(dir, force) {
  const { files, prev, kinds, gone } = survey(dir);
  const stamp = new Date().toISOString().slice(0, 19).replace(/[:T]/g, '-');
  let backups = 0, changed = 0, skipped = 0;
  const backup = (p) => {
    const to = join(dir, BACKUP, stamp, p);
    mkdirSync(dirname(to), { recursive: true });
    copyFileSync(join(dir, p), to);
    backups++;
  };
  const owned = {};
  for (const [p, c] of files) {
    const kind = kinds.get(p);
    if (kind === 'conflict' && !force) {
      console.log(`skip  ${p}: exists and was not generated by the kit; merge it by hand, or --force replaces it (with a backup)`);
      skipped++;
      continue;
    }
    if (p !== 'AGENTS.md') owned[p] = hash(lf(c));
    if (kind === 'same') continue;
    if (kind === 'replace' || kind === 'conflict') { backup(p); console.log(`back  ${p}: ${kind === 'replace' ? 'edited by hand' : 'not generated by the kit'}, replaced`); }
    mkdirSync(dirname(join(dir, p)), { recursive: true });
    writeFileSync(join(dir, p), c);
    changed++;
  }
  writeLock(dir, owned);
  for (const p of gone) {
    const abs = join(dir, p);
    if (!sameHash(prev[p], readFileSync(abs))) backup(p);
    rmSync(abs);
    prune(dir, abs);
    console.log(`del   ${p}`);
  }
  console.log(`Generated files: ${changed} written, ${gone.length} deleted${skipped ? `, ${skipped} skipped` : ''}.`
    + `${backups ? ` Backups: ${BACKUP}/${stamp}/` : ''}`);
}

// Run as a script (not imported). Compare real paths: the module URL has symlinks resolved and argv[1] does not
// (macOS /var → /private/var), and on Windows argv[1] may carry 8.3 names or another drive letter case.
const real = (p) => {
  let r;
  try { r = realpathSync.native(p); } catch { r = resolve(p); }
  return process.platform === 'win32' ? r.toLowerCase() : r;
};
if (process.argv[1] && real(fileURLToPath(import.meta.url)) === real(process.argv[1])) {
  const args = process.argv.slice(2);
  const i = args.indexOf('--dir');
  const dir = i >= 0 ? args[i + 1] : join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', '..');
  if (!statSync(join(dir, '.claude')).isDirectory()) throw new Error(`no .claude/ in ${dir}`);
  if (args.includes('--check')) {
    const s = stale(dir), c = conflicts(dir);
    for (const p of c) console.log(`conflict  ${p}: exists and was not generated by the kit`);
    if (s.length) { console.log(`Generated files are stale; run node ${GENERATOR}\n${s.map((p) => `  ${p}`).join('\n')}`); process.exit(1); }
    console.log('Generated files are current.');
  } else write(dir, args.includes('--force'));
}
